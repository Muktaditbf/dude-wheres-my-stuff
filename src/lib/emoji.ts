export const FALLBACK_EMOJI = '📦';

/** Returns the most fitting emoji for an item name. */
export function emojiFor(name: string): string {
  const key = itemKey(name);
  // "batteries for the remote" is about batteries, not the remote.
  const head = key.split(/\s+(?:for|of|with|from|to)\s+/)[0] ?? key;
  for (const [phrase, emoji] of PHRASES) {
    if (` ${head} `.includes(` ${phrase} `)) return emoji;
  }
  const list = head.split(' ').map(singularize);
  for (let i = list.length - 1; i >= 0; i--) {
    const emoji = WORDS[list[i] ?? ''];
    if (emoji) return emoji;
  }
  return FALLBACK_EMOJI;
}
